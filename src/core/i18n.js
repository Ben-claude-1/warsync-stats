// Ergebnisse werden zwischengespeichert: ein Render erzeugt tausende
// Textknoten, viele davon mit identischem Inhalt, und jeder Durchlauf
// prüft über hundert Muster.
export const _trsCache=new Map();
export function trs(s){
  if(LANG==='de'||!s)return s;
  return trEN(s);
}
// Übersetzt IMMER, auch bei deutscher Oberfläche. Für Inhalte, die die Sprache der
// Oberfläche nicht mitmachen dürfen — konkret das Schluchtsturm-Übersichtsbild:
// das wird als PNG in der Allianz gepostet, und im Spiel heißen die Gebäude englisch.
export function trEN(s){
  if(!s)return s;
  const m=/^(\s*)([\s\S]*?)(\s*)$/.exec(s);
  const core=m[2].replace(/\s+/g,' ');
  if(!core||!/[A-Za-zÄÖÜäöüß]/.test(core))return s;
  const cached=_trsCache.get(core);
  if(cached!==undefined)return cached===null?s:m[1]+cached+m[3];
  const hit=I18N_EN[core];
  if(hit!==undefined){_trsCache.set(core,hit);return m[1]+hit+m[3];}
  // Muster werden verkettet angewandt, nicht nur das erste passende: ein
  // Textknoten enthält oft mehrere übersetzbare Teile (Satz + Zahl + Gebäude).
  // Reihenfolge zählt trotzdem — spezifische Regeln stehen vor generischen,
  // damit die generische nicht wegfrisst, worauf die spezifische zielt.
  let out=core;
  for(let i=0;i<I18N_EN_RE.length;i++){
    const r=I18N_EN_RE[i];
    if(r[0].test(out))out=out.replace(r[0],r[1]);
  }
  if(out!==core){_trsCache.set(core,out);return m[1]+out+m[3];}
  _trsCache.set(core,null);
  I18N_MISS.add(core);
  return s;
}

export const I18N_SKIP={SCRIPT:1,STYLE:1,TEXTAREA:1,PRE:1,CODE:1,SVG:1};
export const I18N_ATTRS=['placeholder','title','aria-label'];
export let _i18nBusy=false;
// Merkt sich je Knoten das zuletzt geschriebene Ergebnis. Ohne das würde ein
// bereits übersetzter Knoten erneut durch trs() laufen — der englische Text
// findet dann keinen Treffer mehr und landet fälschlich in I18N_MISS, und
// halbfertige Muster-Treffer könnten sich gegenseitig überschreiben.
export const _i18nDone=new WeakMap();
export const _i18nAttrDone=new WeakMap();
export function i18nNode(n){
  if(!n)return;
  if(n.nodeType===3){
    const p=n.parentNode;
    if(p&&I18N_SKIP[p.nodeName])return;
    if(_i18nDone.get(n)===n.nodeValue)return;
    const t=trs(n.nodeValue);
    if(t!==n.nodeValue){n.nodeValue=t;_i18nDone.set(n,t);}
    return;
  }
  if(n.nodeType!==1||I18N_SKIP[n.nodeName])return;
  for(let i=0;i<I18N_ATTRS.length;i++){
    const a=I18N_ATTRS[i],v=n.getAttribute(a);
    if(!v)continue;
    let seen=_i18nAttrDone.get(n);
    if(seen&&seen[a]===v)continue;
    const t=trs(v);
    if(t!==v){
      n.setAttribute(a,t);
      if(!seen){seen={};_i18nAttrDone.set(n,seen);}
      seen[a]=t;
    }
  }
  for(let c=n.firstChild;c;c=c.nextSibling)i18nNode(c);
}
export function i18nApply(root){
  if(LANG==='de')return;
  _i18nBusy=true;
  try{i18nNode(root||document.body);}
  finally{if(_i18nObs)_i18nObs.takeRecords();_i18nBusy=false;}
}
export let _i18nObs=null;
export function i18nStart(){
  if(LANG==='de'||_i18nObs)return;
  _i18nObs=new MutationObserver(function(muts){
    if(_i18nBusy)return;
    _i18nBusy=true;
    try{
      for(let i=0;i<muts.length;i++){
        const m=muts[i];
        if(m.type==='childList'){for(let j=0;j<m.addedNodes.length;j++)i18nNode(m.addedNodes[j]);}
        else i18nNode(m.target);
      }
    }finally{_i18nObs.takeRecords();_i18nBusy=false;}
  });
  _i18nObs.observe(document.documentElement,{childList:true,subtree:true,characterData:true,attributes:true,attributeFilter:I18N_ATTRS});
  i18nApply(document.body);
}
